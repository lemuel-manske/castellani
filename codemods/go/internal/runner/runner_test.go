package runner

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	codemods "github.com/lemuel-manske/castellani/codemods/go"
)

func TestRun_CheckReportsDifferencesWithoutWriting(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "example.go")
	source := "package example\n\ntype Service struct{}\n\nconst Name = \"example\"\n"
	writeTestFile(t, path, source)

	changed, err := Run([]string{root}, false, codemods.DeclarationsOrder)
	if err != nil {
		t.Fatal(err)
	}
	if len(changed) != 1 || changed[0] != path {
		t.Fatalf("unexpected changed files: %v", changed)
	}

	assertFile(t, path, source)
}

func TestRun_WriteProducesStableOutput(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "example.go")
	writeTestFile(t, path, "package example\n\ntype Service struct{}\n\nconst Name = \"example\"\n")

	changed, err := Run([]string{root}, true, codemods.DeclarationsOrder)
	if err != nil {
		t.Fatal(err)
	}
	if len(changed) != 1 || changed[0] != path {
		t.Fatalf("expected one written file, got %v", changed)
	}
	assertFile(t, path, "package example\n\nconst Name = \"example\"\n\ntype Service struct{}\n")

	changed, err = Run([]string{root}, false, codemods.DeclarationsOrder)
	if err != nil {
		t.Fatal(err)
	}
	if len(changed) != 0 {
		t.Fatalf("second run unexpectedly changed files: %v", changed)
	}
}

func TestRun_SkipsGeneratedAndFixtureFiles(t *testing.T) {
	root := t.TempDir()
	generated := filepath.Join(root, "generated.go")
	fixture := filepath.Join(root, "testdata", "fixture.go")
	vendor := filepath.Join(root, "vendor", "vendor.go")
	content := "package example\n\ntype Service struct{}\n\nconst Name = \"example\"\n"
	writeTestFile(t, generated, "// Code generated by sample; DO NOT EDIT.\n"+content)
	writeTestFile(t, fixture, content)
	writeTestFile(t, vendor, content)

	changed, err := Run([]string{root}, true, codemods.DeclarationsOrder)
	if err != nil {
		t.Fatal(err)
	}
	if len(changed) != 0 {
		t.Fatalf("unexpected changed files: %v", changed)
	}

	assertFile(t, generated, "// Code generated by sample; DO NOT EDIT.\n"+content)
	assertFile(t, fixture, content)
	assertFile(t, vendor, content)
}

func TestRun_HandlesOverlappingDirectoriesWithoutDuplicateWrites(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "sub", "example.go")
	writeTestFile(t, path, "package example\n\ntype Service struct{}\n\nconst Name = \"example\"\n")

	changed, err := Run([]string{root, filepath.Join(root, "sub"), path}, false, codemods.DeclarationsOrder)
	if err != nil {
		t.Fatal(err)
	}
	if len(changed) != 1 || changed[0] != path {
		t.Fatalf("expected one changed file, got %v", changed)
	}
}

func TestRun_InvalidFileDoesNotModifyEarlierFiles(t *testing.T) {
	root := t.TempDir()
	valid := filepath.Join(root, "a.go")
	invalid := filepath.Join(root, "z.go")
	source := "package example\n\ntype Service struct{}\n\nconst Name = \"example\"\n"
	writeTestFile(t, valid, source)
	writeTestFile(t, invalid, "package example\nfunc broken( {\n")

	_, err := Run([]string{root}, true, codemods.DeclarationsOrder)
	if err == nil || !strings.Contains(err.Error(), "z.go") {
		t.Fatalf("expected named parse error, got %v", err)
	}

	assertFile(t, valid, source)
}

func TestRun_PreservesFilePermissions(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "example.go")
	writeTestFile(t, path, "package example\n\ntype Service struct{}\n\nconst Name = \"example\"\n")
	if err := os.Chmod(path, 0o640); err != nil {
		t.Fatal(err)
	}

	_, err := Run([]string{path}, true, codemods.DeclarationsOrder)
	if err != nil {
		t.Fatal(err)
	}

	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0o640 {
		t.Fatalf("permissions changed to %v", info.Mode().Perm())
	}
}

func writeTestFile(t *testing.T, path, source string) {
	t.Helper()

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
}

func assertFile(t *testing.T, path, expected string) {
	t.Helper()

	actual, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(actual) != expected {
		t.Errorf("unexpected file contents\nexpected:\n%s\nactual:\n%s", expected, actual)
	}
}
